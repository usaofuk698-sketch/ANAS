/** يزيل التشكيل ويوحّد الألف والهمزات لتحسين المطابقة */
export function normalizeArabic(text){
  return String(text)
    .replace(/[ً-ْٰـ]/g, '')   // التشكيل والتطويل
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[ؤئ]/g, 'ء')
    .toLowerCase()
    .trim();
}

const STOP_WORDS = new Set([
  'ما', 'هو', 'هي', 'من', 'عن', 'في', 'على', 'الى', 'ال', 'كيف', 'لماذا', 'متى',
  'هل', 'ماهو', 'ماهي', 'اين', 'التي', 'الذي', 'كم', 'مع', 'بين', 'و', 'يا',
  'شنو', 'وش', 'ايش', 'اخبرني', 'اشرح', 'لي', 'عندك', 'معلومات',
]);

const tokenize = (text) =>
  normalizeArabic(text)
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => word.length > 1 && !STOP_WORDS.has(word));

/** يحسب درجة تطابق نص مع كلمات السؤال */
function scoreText(tokens, text, weight = 1){
  const haystack = normalizeArabic(text);
  let score = 0;
  for (const token of tokens){
    if (haystack.includes(token)) score += weight * (token.length >= 4 ? 1.4 : 1);
  }
  return score;
}

/**
 * يبحث عن أفضل إجابة محلية.
 * @returns {{ kind:'concept'|'specimen'|'none', score:number, ... }}
 */
export function findAnswer(question){
  const tokens = tokenize(question);
  if (!tokens.length) return { kind: 'none', score: 0 };

  const candidates = [];

  for (const concept of CONCEPTS){
    const score =
      scoreText(tokens, concept.keywords.join(' '), 3) +
      scoreText(tokens, concept.title, 2) +
      scoreText(tokens, concept.answer, .35);
    if (score > 0) candidates.push({ kind: 'concept', score, concept });
  }

  for (const specimen of SPECIMENS){
    const score =
      scoreText(tokens, specimen.name, 3.5) +
      scoreText(tokens, specimen.latin, 3) +
      scoreText(tokens, categoryLabel(specimen.category), 1.4) +
      scoreText(tokens, specimen.summary, .7) +
      scoreText(tokens, specimen.habitat, .7) +
      scoreText(tokens, specimen.body, .3);
    if (score > 0) candidates.push({ kind: 'specimen', score, specimen });
  }

  if (!candidates.length) return { kind: 'none', score: 0 };

  candidates.sort((a, b) => b.score - a.score);
  return { ...candidates[0], related: candidates.slice(1, 4) };
}

/** يبني نص الإجابة النهائي من نتيجة المطابقة */
export function composeAnswer(question, match){
  if (match.kind === 'none' || match.score < 1.2){
    return {
      text: 'لم أجد إجابة دقيقة لهذا السؤال في قاعدة معرفتي المحلية.\n\nأنا أعمل حالياً **بدون اتصال بأي نموذج ذكاء اصطناعي** — أجيب من مقالات وعيّنات مكتوبة مسبقاً داخل المنصة. جرّب صياغة أبسط، أو اسأل عن أحد هذه الموضوعات: الفرق بين الفيروس والبكتيريا، مقاومة المضادات الحيوية، الحمض النووي، الميكروبيوم، أو أي عيّنة في المكتبة.',
      links: [{ label: 'تصفّح المكتبة العلمية', href: '#/library' }],
    };
  }

  if (match.kind === 'concept'){
    return {
      text: `**${match.concept.title}**\n\n${match.concept.answer}`,
      links: relatedLinks(match.related),
    };
  }

  const specimen = match.specimen;
  const facts = specimen.facts.slice(0, 2).map((fact) => `• ${fact}`).join('\n');

  return {
    text:
      `**${specimen.name}** (${specimen.latin})\n\n` +
      `${specimen.summary}\n\n` +
      `${specimen.body}\n\n` +
      `**الحجم:** ${formatSize(specimen.sizeText)}\n` +
      `**البيئة:** ${specimen.habitat}\n` +
      `**الاكتشاف:** ${specimen.discovered}\n\n` +
      `**حقائق سريعة:**\n${facts}`,
    links: [
      { label: `افتح الملف الكامل لـ${specimen.name}`, href: `#/library/${specimen.id}` },
      { label: 'افحصها تحت المجهر', href: `#/microscope?specimen=${specimen.id}` },
      ...relatedLinks(match.related),
    ].slice(0, 4),
  };
}

function relatedLinks(related = []){
  return related
    .filter((item) => item.kind === 'specimen')
    .slice(0, 2)
    .map((item) => ({ label: `اقرأ عن ${item.specimen.name}`, href: `#/library/${item.specimen.id}` }));
}

