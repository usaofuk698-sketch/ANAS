/** عدد العيّنات في كل تصنيف */
export function categoryCounts(){
  const counts = { all: SPECIMENS.length };
  for (const specimen of SPECIMENS){
    counts[specimen.category] = (counts[specimen.category] ?? 0) + 1;
  }
  return counts;
}

/** بحث وفلترة وترتيب */
export function searchSpecimens({ query = '', category = 'all', sort = 'name' } = {}){
  const normalized = query.trim().toLowerCase();

  let results = SPECIMENS.filter((specimen) => {
    if (category !== 'all' && specimen.category !== category) return false;
    if (!normalized) return true;
    return [specimen.name, specimen.latin, specimen.summary, specimen.habitat]
      .join(' ').toLowerCase().includes(normalized);
  });

  const sorters = {
    name:      (a, b) => a.name.localeCompare(b.name, 'ar'),
    sizeAsc:   (a, b) => a.sizeUm - b.sizeUm,
    sizeDesc:  (a, b) => b.sizeUm - a.sizeUm,
    category:  (a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name, 'ar'),
  };
  results = [...results].sort(sorters[sort] ?? sorters.name);

  return results;
}

