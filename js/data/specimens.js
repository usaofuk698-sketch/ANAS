/**
 * يعزل الجزء الرقمي من نص الحجم ليُقرأ يساراً-يميناً.
 *
 * بدون هذا ينعكس النطاق داخل الفقرة العربية: الشرطة و«×»
 * محايدتان اتجاهياً، فيعيد محرّك الـ bidi ترتيب الطرفين
 * ويظهر «0.05–1.2» على شكل «1.2–0.05».
 * نستخدم محرفي العزل U+2066/U+2069 فيبقى النص عادياً
 * بلا أي وسوم HTML.
 */
export function formatSize(sizeText){
  return String(sizeText).replace(
    /^[\d.,×\s\u2013\u2014-]+/,
    (numeric) => '\u2066' + numeric.trim() + '\u2069 ',
  );
}

